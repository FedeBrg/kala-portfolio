#!/usr/bin/env python3
"""Regenerate content/fallback.js from content/projects.json and content/settings.json.

The site normally fetches the JSON files. Browsers block fetch() when index.html is opened
straight from disk (file://), so the page then loads this snapshot instead.
Run from the repo root:  python3 tools/build-fallback.py
"""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
projects = json.loads((root / "content/projects.json").read_text(encoding="utf-8"))
settings = json.loads((root / "content/settings.json").read_text(encoding="utf-8"))
data = {"projects": projects.get("projects", []), "settings": settings}
out = "// Generated by tools/build-fallback.py: offline snapshot used only when the page is opened from disk.\n"
out += "window.PORTFOLIO_FALLBACK = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n"
(root / "content/fallback.js").write_text(out, encoding="utf-8")
print("wrote content/fallback.js with", len(data["projects"]), "projects")
